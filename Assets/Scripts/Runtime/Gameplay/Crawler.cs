using EchoMaze.Core;
using EchoMaze.Data;
using UnityEngine;

namespace EchoMaze.Gameplay
{
    /// <summary>
    /// The Crawler: two round bumps with a gap between them. That shape *is* the enemy — the ray pipeline
    /// measures the two colliders like any other geometry and the wave shows two circles where a wall would
    /// show one line, so no code here describes what the creature looks like to the player.
    ///
    /// Detection in week 2 is a documented stub: contact kills, and a noise inside the straight-line hearing
    /// radius H = rho * R(L) makes it walk toward the noise and stand still there for a moment. Week 3
    /// replaces this with EnemyBrain (suspicion meter, Dormant / Patrol / Curious / Investigate / Chase /
    /// Lost) fed by NoiseBoard, which is where walls, closed doors, noise zones and hollows enter hearing at
    /// all. There is no pathfinding: a hunt that runs into a wall is cut short by huntSeconds, which is the
    /// stub's honest limit and the reason it must not quietly become permanent.
    /// </summary>
    [RequireComponent(typeof(Rigidbody2D))]
    public sealed class Crawler : MonoBehaviour
    {
        enum Mode
        {
            Patrol,
            Wait,
            Investigate
        }

        [SerializeField] EchoDirector director;
        [SerializeField] Player player;

        [Tooltip("World positions walked between, in order, looping. Kept as numbers because the blockout is " +
                 "generated by an editor script; a designer authoring a real level gets these in the inspector.")]
        [SerializeField] Vector2[] patrolPoints;
        [Tooltip("Distance at which a waypoint counts as reached.")]
        [SerializeField, Range(0.05f, 1f)] float arrivalRadius = 0.25f;
        [Tooltip("Paused between waypoints are drawn from this seed, so a run can be replayed exactly. The " +
                 "week 4 bot depends on it; a random pause would make every simulation incomparable.")]
        [SerializeField] int seed = 1;
        [SerializeField, Range(0f, 5f)] float pauseMinSeconds = 0.6f;
        [SerializeField, Range(0f, 5f)] float pauseMaxSeconds = 2.4f;
        [Tooltip("Seconds spent standing at a noise it heard before losing interest. Fixed, not seeded: here " +
                 "the stillness is the information the player is meant to read.")]
        [SerializeField, Range(0.2f, 8f)] float lookAroundSeconds = 2f;
        [Tooltip("A hunt is abandoned after this long, because with no pathfinding it is probably pressed " +
                 "against a wall by now.")]
        [SerializeField, Range(0.5f, 15f)] float huntSeconds = 4f;
        [Tooltip("Multiplies the profile's footstep interval: the Crawler drags, so its rhythm must not be " +
                 "the player's.")]
        [SerializeField, Range(0.2f, 4f)] float stepRhythm = 1.35f;

        Rigidbody2D body;
        Vector2 startPosition;
        Mode mode;
        int leg;
        float resumeAt;
        float huntDeadline;
        Vector2 huntTarget;
        float nextStepTime;
        System.Random pauseRandom;

        public Vector2 Position => transform.position;
        public bool IsHunting => mode == Mode.Investigate;

        EchoTuningProfile Profile => director != null ? director.Profile : null;

        void Awake()
        {
            body = GetComponent<Rigidbody2D>();
            startPosition = transform.position;
            pauseRandom = new System.Random(seed);

            if (director == null)
            {
                Debug.LogError(name + " has no EchoDirector reference: it cannot hear anything. Rebuild the " +
                               "scene with Tools/Echo Maze.", this);
            }

            if (player == null)
            {
                Debug.LogError(name + " has no Player reference: touching it will not kill anyone. Rebuild " +
                               "the scene with Tools/Echo Maze.", this);
            }
        }

        void OnEnable()
        {
            if (director != null)
            {
                director.NoiseEmitted += OnNoise;
            }
        }

        void OnDisable()
        {
            if (director != null)
            {
                director.NoiseEmitted -= OnNoise;
            }
        }

        void FixedUpdate()
        {
            EchoTuningProfile profile = Profile;
            if (profile == null || patrolPoints == null || patrolPoints.Length == 0)
            {
                body.linearVelocity = Vector2.zero;
                return;
            }

            if (mode == Mode.Investigate && Time.time >= huntDeadline)
            {
                mode = Mode.Patrol;
                leg = NextLeg();
            }

            if (mode == Mode.Wait)
            {
                body.linearVelocity = Vector2.zero;
                if (Time.time >= resumeAt)
                {
                    mode = Mode.Patrol;
                    leg = NextLeg();
                }

                return;
            }

            Vector2 destination = mode == Mode.Investigate ? huntTarget : patrolPoints[leg];
            Vector2 to = destination - (Vector2)transform.position;
            float distance = to.magnitude;

            if (distance <= arrivalRadius)
            {
                body.linearVelocity = Vector2.zero;
                bool arrivedAtANoise = mode == Mode.Investigate;
                mode = Mode.Wait;
                resumeAt = Time.time + (arrivedAtANoise
                    ? lookAroundSeconds
                    : Mathf.Lerp(pauseMinSeconds, pauseMaxSeconds, (float)pauseRandom.NextDouble()));
                return;
            }

            float speed = profile.walkSpeed * profile.crawlerSpeedMultiplier;
            body.linearVelocity = to / distance * speed;
            EmitStep(profile);
        }

        void EmitStep(EchoTuningProfile profile)
        {
            if (director == null || Time.time < nextStepTime)
            {
                return;
            }

            nextStepTime = Time.time + profile.footstepInterval * stepRhythm;

            // Week 2 has no ear for this yet: the player hears enemy footsteps when landmark audio lands in
            // week 4. It is emitted now because the noise stream is the only honest place for it, and the
            // day 5 debug window reads it back as a position.
            director.ReportNoise(transform.position, profile.footstepLoudness);
        }

        void OnNoise(Vector2 position, float loudness)
        {
            EchoTuningProfile profile = Profile;
            if (profile == null)
            {
                return;
            }

            float distance = Vector2.Distance(position, transform.position);

            // Its own footsteps are emitted at its own position, and a creature that startled at its own
            // walking would never patrol. NoiseBoard (week 3) is where friend-or-foe gets decided properly.
            if (distance < arrivalRadius)
            {
                return;
            }

            if (distance > ArcMath.HearingRadius(loudness, profile))
            {
                return;
            }

            huntTarget = position;
            huntDeadline = Time.time + huntSeconds;
            mode = Mode.Investigate;
        }

        void OnCollisionEnter2D(Collision2D collision)
        {
            if (player == null || !player.IsAlive)
            {
                return;
            }

            if (collision.collider.GetComponentInParent<Player>() != null)
            {
                player.Die();
            }
        }

        /// <summary>
        /// Puts the creature back the way the run started: same spawn, same first leg, and a fresh RNG on
        /// the same seed, so the retry patrols identically instead of differently.
        /// </summary>
        public void ResetRun()
        {
            transform.position = startPosition;
            body.linearVelocity = Vector2.zero;
            mode = Mode.Patrol;
            leg = 0;
            resumeAt = 0f;
            huntDeadline = 0f;
            nextStepTime = 0f;
            pauseRandom = new System.Random(seed);
        }

        int NextLeg() => (leg + 1) % patrolPoints.Length;
    }
}
